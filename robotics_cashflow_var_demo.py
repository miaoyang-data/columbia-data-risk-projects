"""
Robotics Asset-Backed Cash Flow Stress Testing & Value at Risk (VaR) Engine
Fleetscale Micro-Project Technical Demo

Author: Miao Yang (Columbia University MS ERM)
Description:
    Quantifies downside tail risk and credit guardrails for Robotics-as-a-Service (RaaS) asset pools.
    Incorporates end-market demand cyclicality, labor cost savings, and Monte Carlo scenario testing.
"""

import numpy as np
import pandas as pd


def simulate_robotics_portfolio_cashflow(
    n_robots=50,
    monthly_labor_savings_per_robot=4500,
    fleetscale_revenue_share=0.40,
    depreciation_rate_annual=0.15,
    cyclicality_volatility=0.25,
    months=12,
    num_simulations=5000,
    seed=42,
):
    """Simulates monthly cash flows for a robotics leasing portfolio considering end-market cyclicality.

    Parameters:
        n_robots (int): Total active fleet size.
        monthly_labor_savings_per_robot (float): Cost saved vs human labor per unit ($).
        fleetscale_revenue_share (float): % of generated value captured by Fleetscale.
        depreciation_rate_annual (float): Annual hardware value/yield decay rate.
        cyclicality_volatility (float): End-market industry demand volatility.
        months (int): Horizon of underwriting (12 months).
        num_simulations (int): Monte Carlo paths for tail-risk analysis.
    """
    np.random.seed(seed)

    # Base monthly expected revenue generated per robot
    base_monthly_revenue = (
        monthly_labor_savings_per_robot * fleetscale_revenue_share
    )
    monthly_depr = depreciation_rate_annual / 12.0

    simulation_results = []

    for sim in range(num_simulations):
        total_annual_cashflow = 0
        for m in range(months):
            # Asset efficiency decay
            asset_efficiency = (1 - monthly_depr) ** m

            # End-market demand shock (Macro/Industry Cyclicality)
            demand_shock = np.random.normal(0, cyclicality_volatility / np.sqrt(12))
            cyclicality_factor = max(0.2, 1.0 + demand_shock)

            # Net Monthly Revenue generated by the active fleet
            monthly_fleet_cashflow = (
                n_robots
                * base_monthly_revenue
                * asset_efficiency
                * cyclicality_factor
            )
            total_annual_cashflow += monthly_fleet_cashflow

        simulation_results.append(total_annual_cashflow)

    return np.array(simulation_results)


def calculate_risk_guardrails(cashflow_distribution, confidence_level=0.95):
    """Calculates Portfolio Value at Risk (VaR) and sets credit underwriting guardrails."""
    expected_cashflow = np.mean(cashflow_distribution)

    # 95% 1-Year Value at Risk (VaR) relative to expected cash flow
    percentile_val = np.percentile(
        cashflow_distribution, (1 - confidence_level) * 100
    )
    var_95 = expected_cashflow - percentile_val

    # Credit Risk Guardrail: Minimum debt coverage threshold
    stressed_annual_cashflow = percentile_val
    recommended_max_debt_underwriting = stressed_annual_cashflow * 0.75

    print(
        f"=================== FLEETSCALE RISK GUARDRAIL SUMMARY ==================="
    )
    print(f"Expected 1-Year Fleet Cash Flow:       ${expected_cashflow:,.2f}")
    print(
        f"Stressed Cash Flow (95% Confidence):   ${stressed_annual_cashflow:,.2f}"
    )
    print(
        f"95% 1-Year Portfolio Value at Risk:    ${var_95:,.2f} ({var_95/expected_cashflow:.1%} tail loss)"
    )
    print(
        f"Recommended Underwriting Credit Limit: ${recommended_max_debt_underwriting:,.2f}"
    )
    print(
        f"========================================================================"
    )

    return {
        "expected_cashflow": expected_cashflow,
        "stressed_cashflow": stressed_annual_cashflow,
        "var_95": var_95,
        "max_debt_limit": recommended_max_debt_underwriting,
    }


if __name__ == "__main__":
    print(
        "Running Fleetscale Robotics Asset Cash Flow & VaR Simulation Engine...\n"
    )

    # Simulate portfolio of 50 deployed robots in manufacturing/logistics
    portfolio_cashflows = simulate_robotics_portfolio_cashflow(
        n_robots=50,
        monthly_labor_savings_per_robot=4500,
        fleetscale_revenue_share=0.40,
        cyclicality_volatility=0.25,
    )

    # Output underwriting risk guardrails
    calculate_risk_guardrails(portfolio_cashflows, confidence_level=0.95)
